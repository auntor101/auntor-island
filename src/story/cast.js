// First meeting: a few lines, then a question with two answers, one reply each (and an optional closing line). 3 to 5 boxes.
function meet(who, pre, opts, replies, post) {
  const nodes = pre.map((text, i) => ({ id: i ? 'p' + i : 'start', who, text, next: 'p' + (i + 1) }));
  const last = nodes[nodes.length - 1];
  delete last.next; last.choices = opts.map((text, i) => ({ text, next: 'r' + i, set: { [`met_${who}_${i}`]: true } }));
  replies.forEach((text, i) => nodes.push({ id: 'r' + i, who, text, next: post ? 'post' : undefined }));
  if (post) nodes.push({ id: 'post', who, text: post });
  return nodes;
}

